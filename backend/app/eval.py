"""Evaluate detection on the synthetic dataset: python -m app.eval"""
from __future__ import annotations

import argparse
import math
import time
from collections import defaultdict
from pathlib import Path

import cv2

from .detect import detect
from .fold_utils import merge_collinear_lines
from .synth import LEVELS, make_dataset
from .validate import validate

MATCH_TOL = 0.015
REPORT = Path(__file__).resolve().parents[2] / "docs" / "eval_results.md"


def crease_segments(fold: dict) -> list[tuple[tuple, tuple, str]]:
    """Maximal collinear runs of edges that share one assignment (M/V/F)."""
    coords = fold["vertices_coords"]
    out = []
    for line in merge_collinear_lines(fold):
        # edges come ordered along the line; split where the assignment changes
        run: list[int] = []
        for e, a in zip(line["edges"], line["assignments"]):
            if run and fold["edges_assignment"][run[-1]] != a:
                out.append(_run_to_seg(fold, coords, run))
                run = []
            run.append(e)
        if run:
            out.append(_run_to_seg(fold, coords, run))
    return out


def _run_to_seg(fold, coords, run):
    pts = [tuple(coords[v]) for e in run for v in fold["edges_vertices"][e]]
    a = max(pts, key=lambda p: math.dist(p, pts[0]))
    b = max(pts, key=lambda p: math.dist(p, a))
    return a, b, fold["edges_assignment"][run[0]]


def _same_geometry(s, t) -> bool:
    (a, b, _), (c, d, _) = s, t
    return ((math.dist(a, c) <= MATCH_TOL and math.dist(b, d) <= MATCH_TOL)
            or (math.dist(a, d) <= MATCH_TOL and math.dist(b, c) <= MATCH_TOL))


def match(pred: list, gt: list) -> dict:
    """Greedy one-to-one matching. A match needs the same geometry; P/R/F1 also need the same assignment."""
    used: set[int] = set()
    geo_pairs = []
    for i, p in enumerate(pred):
        for j, g in enumerate(gt):
            if j not in used and _same_geometry(p, g):
                used.add(j)
                geo_pairs.append((i, j))
                break
    tp = sum(1 for i, j in geo_pairs if pred[i][2] == gt[j][2])
    mv_pairs = [(i, j) for i, j in geo_pairs if gt[j][2] in ("M", "V")]
    mv_ok = sum(1 for i, j in mv_pairs if pred[i][2] == gt[j][2])
    return {"tp": tp, "n_pred": len(pred), "n_gt": len(gt),
            "mv_ok": mv_ok, "mv_n": len(mv_pairs)}


def _prf(tp, n_pred, n_gt):
    p = tp / n_pred if n_pred else 1.0
    r = tp / n_gt if n_gt else 1.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f


def evaluate(n: int = 40, seed: int = 0, out_dir: Path | None = None) -> dict:
    items = make_dataset(n=n, seed=seed, out_dir=out_dir)
    agg: dict[str, dict] = defaultdict(lambda: defaultdict(float))
    for it in items:
        img = cv2.imread(str(it["png"]))
        t0 = time.perf_counter()
        res = detect(img)
        dt = time.perf_counter() - t0
        m = match(crease_segments(res["fold"]), crease_segments(it["fold"]))
        for key in (it["level"], "all"):
            a = agg[key]
            a["count"] += 1
            for k, v in m.items():
                a[k] += v
            ok = validate(res["fold"])["ok"]
            a["valid"] += 1 if ok else 0
            if validate(it["fold"])["ok"]:
                a["gt_valid"] += 1
                a["valid_when_gt"] += 1 if ok else 0
            a["time"] += dt
    summary = {}
    for key in list(LEVELS) + ["all"]:
        a = agg.get(key)
        if not a:
            continue
        p, r, f = _prf(a["tp"], a["n_pred"], a["n_gt"])
        summary[key] = {
            "n": int(a["count"]),
            "precision": p,
            "recall": r,
            "f1": f,
            "mv_accuracy": a["mv_ok"] / a["mv_n"] if a["mv_n"] else 1.0,
            "valid_pct": 100 * a["valid"] / a["count"],
            "valid_when_gt_pct": 100 * a["valid_when_gt"] / a["gt_valid"] if a["gt_valid"] else float("nan"),
            "runtime_s": a["time"] / a["count"],
        }
    return summary


def write_report(summary: dict, path: Path = REPORT) -> None:
    rows = ["| Augmentation | Images | Precision | Recall | F1 | M/V accuracy | Validates | Validates (GT-valid only) | Mean runtime |",
            "|---|---|---|---|---|---|---|---|---|"]
    for key, s in summary.items():
        rows.append(
            f"| {key} | {s['n']} | {s['precision']:.3f} | {s['recall']:.3f} | {s['f1']:.3f} | "
            f"{s['mv_accuracy']:.3f} | {s['valid_pct']:.0f}% | {s['valid_when_gt_pct']:.0f}% | "
            f"{s['runtime_s'] * 1000:.0f} ms |"
        )
    text = "\n".join([
        "# Detection evaluation (synthetic)",
        "",
        "Generated by `python -m app.eval`. The dataset is the built-in library plus random",
        "8×8 / 16×16 grid crease patterns with 22.5° lines, rendered by `app/synth.py`.",
        "",
        "- **clean**: the rendering as-is.",
        "- **mild**: Gaussian noise, blur and JPEG quality 60.",
        "- **hard**: mild + ±5° rotation, perspective warp and a grey desk background.",
        "",
        "A predicted crease matches a ground-truth crease when both endpoints are within 1.5% of the",
        "side and the assignment agrees. M/V accuracy is measured on geometrically matched M/V creases.",
        "“Validates” is the share of detected patterns passing Maekawa and Kawasaki at every vertex.",
        "Random CPs are usually not flat-foldable themselves, so the next column only counts images",
        "whose ground truth validates (the library models).",
        "",
        *rows,
        "",
    ])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("-n", type=int, default=40)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    t0 = time.perf_counter()
    summary = evaluate(args.n, args.seed)
    write_report(summary)
    for k, s in summary.items():
        print(f"{k:6s} P={s['precision']:.3f} R={s['recall']:.3f} F1={s['f1']:.3f} "
              f"MV={s['mv_accuracy']:.3f} valid={s['valid_pct']:.0f}% "
              f"valid|gt={s['valid_when_gt_pct']:.0f}% t={s['runtime_s']*1000:.0f}ms")
    print(f"total {time.perf_counter() - t0:.1f}s, report: {REPORT}")


if __name__ == "__main__":
    main()
